/** Normalize NFC and whitespace for feature lookup. */
export function normalizeFeatureKey(tr: string) {
  return tr.normalize('NFC').replace(/\s+/g, ' ').trim()
}

export function translateFeature(tr: string): {tr: string; en: string; ar: string} {
  const key = normalizeFeatureKey(tr)
  const hit = featureI18n[key]
  if (hit) return {tr: key, en: hit.en, ar: hit.ar}
  // Tolerate minor unicode differences (e.g. composed ü)
  for (const [source, value] of Object.entries(featureI18n)) {
    if (normalizeFeatureKey(source) === key) return {tr: key, en: value.en, ar: value.ar}
  }
  return {tr: key, en: key, ar: key}
}
